#Requires -Version 5.1
<#
.SYNOPSIS
Generate the command reference from module metadata and comment-based help.
.PARAMETER OutputPath
Destination file; defaults to docs/commands.md in the repository.
#>
[CmdletBinding()]
param(
    [string]$OutputPath = (Join-Path (Split-Path $PSScriptRoot -Parent) 'docs/commands.md')
)

$ErrorActionPreference = 'Stop'
$manifest = Join-Path (Split-Path $PSScriptRoot -Parent) 'DbxToolbox/DbxToolbox.psd1'
$module = Import-Module $manifest -Force -PassThru

# Read in module scope so the ordered alias map remains the single source of truth.
$rows = & $module {
    $aliases = [ordered]@{}
    foreach ($name in $script:Aliases.Keys) { $aliases[$name] = $script:Aliases[$name] }
    $aliases['dbx-help'] = 'Show-DbxHelp'
    foreach ($name in $aliases.Keys) {
        $command = Get-Command $aliases[$name]
        # Show the name people type: a parameter's alias if it has one (-Profile, not -CliProfile).
        [string[]]$parameters = @($command.Parameters.Values | Where-Object {
            $_.Name -notin [System.Management.Automation.PSCmdlet]::CommonParameters -and
            $_.Name -notin [System.Management.Automation.PSCmdlet]::OptionalCommonParameters
        } | ForEach-Object { if ($_.Aliases.Count) { $_.Aliases[0] } else { $_.Name } })
        [Array]::Sort($parameters, [StringComparer]::Ordinal)
        [pscustomobject]@{
            Alias = $name
            Function = $command.Name
            Asks = if ($command.Parameters.ContainsKey('WhatIf')) { 'yes' } else { 'no' }
            Synopsis = (Get-Help $command.Name).Synopsis
            Parameters = ($parameters | ForEach-Object { '`-{0}`' -f $_ }) -join ', '
        }
    }
}

$lines = @(
    '# DbxToolbox command reference'
    ''
    'Generated by `scripts/Build-Docs.ps1`; do not edit by hand. `Get-Help <function> -Full` shows'
    'the details of any command; commands marked "asks first" also take `-WhatIf` and `-Confirm`.'
    ''
    '| Command | Function name | Asks first | Synopsis | Parameters |'
    '| --- | --- | --- | --- | --- |'
    foreach ($row in $rows) {
        $synopsis = ([string]$row.Synopsis -replace '\s+', ' ').Trim().Replace('|', '&#124;')
        '| `{0}` | {1} | {2} | {3} | {4} |' -f $row.Alias, $row.Function, $row.Asks, $synopsis, $row.Parameters
    }
)
$content = ($lines -join "`n") + "`n"
if ($content -match '[^\x00-\x7F]') { throw 'Command reference must contain ASCII characters only.' }
$destination = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($OutputPath)
$null = [System.IO.Directory]::CreateDirectory((Split-Path $destination -Parent))
[System.IO.File]::WriteAllText($destination, $content, (New-Object System.Text.UTF8Encoding $false))
